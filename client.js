    /**
     * Pick the fallback language from the browser's ordered language list.
     * @returns {"zh"|"en"} the fallback language id.
     */
    function detectLocale() {
      try {
        const languages = typeof navigator === 'undefined' ? undefined : navigator.languages
        const first = Array.isArray(languages) ? languages[0] : undefined
        const tag = String(first ?? (typeof navigator === 'undefined' ? '' : navigator.language) ?? '').toLowerCase()
        return tag.startsWith('zh') ? 'zh' : 'en'
      } catch {
        return 'en'
      }
    }

    /** @returns {"zh"|"en"} the cached fallback language id. */
    function currentFallbackLang() {
      if (fallbackLang === null) fallbackLang = detectLocale()
      return fallbackLang
    }

