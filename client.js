    /**
     * Colours for the glyph presets: every bundled icon gets its own hue.
     *
     * The hue is the icon's index in the catalog times the golden angle, which
     * spreads all presets evenly around the wheel and makes neighbours in the
     * picker as different as the wheel allows. Colours are built in OKLCH, where
     * equal numbers read as equally bright, then converted to sRGB hex: a hue at
     * the lightness of a blue would otherwise read far brighter as a yellow.
     * Each hue takes as much chroma as sRGB can hold under a fixed cap, so the
     * whole set stays vivid without clipping.
     */
    const GLYPH_HUE_STEP = 137.50776405003785
    const GLYPH_LIGHTNESS = 0.6
    const GLYPH_CHROMA_CAP = 0.17
    const GLYPH_CHROMA_HEADROOM = 0.94

    /** Encode one linear-light channel as an sRGB 0–1 value. */
    function srgbEncode(linear) {
      return linear <= 0.0031308 ? 12.92 * linear : 1.055 * linear ** (1 / 2.4) - 0.055
    }

    /**
     * One OKLCH colour as clamped sRGB channels.
     * @param {number} lightness - OKLab L, 0–1.
     * @param {number} chroma - OKLab chroma.
     * @param {number} hue - OKLab hue in degrees.
     * @returns {number[]} `[r, g, b]`, each 0–1 (clipped to the sRGB cube).
     */
    function oklchToRgb(lightness, chroma, hue) {
      const radians = (hue * Math.PI) / 180
      const a = chroma * Math.cos(radians)
      const b = chroma * Math.sin(radians)
      const l = (lightness + 0.3963377774 * a + 0.2158037573 * b) ** 3
      const m = (lightness - 0.1055613458 * a - 0.0638541728 * b) ** 3
      const s = (lightness - 0.0894841775 * a - 1.2914855480 * b) ** 3
      const clamp = (value) => Math.min(1, Math.max(0, value))
      return [
        clamp(srgbEncode(4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s)),
        clamp(srgbEncode(-1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s)),
        clamp(srgbEncode(-0.0041960863 * l - 0.7034186147 * m + 1.7076147010 * s)),
      ]
    }

    /** Whether a colour survived the trip through sRGB without clipping. */
    function withinGamut(lightness, chroma, hue) {
      return oklchToRgb(lightness, chroma, hue).every((channel) => channel > 0 && channel < 1)
    }

    /**
     * The most chroma sRGB can hold for one hue at our fixed lightness.
     * @param {number} hue - OKLab hue in degrees.
     * @returns {number} the largest in-gamut chroma.
     */
    function maxChroma(hue) {
      let low = 0
      let high = 0.4
      for (let step = 0; step < 22; step += 1) {
        const mid = (low + high) / 2
        if (withinGamut(GLYPH_LIGHTNESS, mid, hue)) low = mid
        else high = mid
      }
      return low
    }

    /** `name → '#rrggbb'`, built once per glyph. */
    const glyphColorCache = new Map()

    /**
     * The preset colour of one glyph: its own hue, at an even lightness.
     * @param {string} name - bundled glyph name.
     * @returns {string} a `#rrggbb` colour, or '' when the name is not bundled.
     */
    function glyphColor(name) {
      if (!GLYPH_NAME_SET.has(name)) return ''
      const cached = glyphColorCache.get(name)
      if (cached !== undefined) return cached
      const hue = (GLYPH_NAMES.indexOf(name) * GLYPH_HUE_STEP) % 360
      const chroma = Math.min(GLYPH_CHROMA_CAP, maxChroma(hue) * GLYPH_CHROMA_HEADROOM)
      const channels = oklchToRgb(GLYPH_LIGHTNESS, chroma, hue).map((value) =>
        Math.round(value * 255).toString(16).padStart(2, '0'),
      )
      const color = `#${channels.join('')}`
      glyphColorCache.set(name, color)
      return color
    }

