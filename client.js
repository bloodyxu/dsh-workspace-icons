    /**
     * Does this project still need a suggestion?
     * @param {unknown} workspace - a workspace view.
     * @returns {boolean} true when it has no manual icon and no suggestion.
     */
    function needsSuggestion(workspace) {
      const key = iconKey(workspace)
      if (key === '') return false
      const path = typeof workspace.path === 'string' ? workspace.path.trim() : ''
      if (path === '' || !path.startsWith('/')) return false
      if (Object.hasOwn(iconStore.value, key)) return false
      return !Object.hasOwn(autoStore.value.byPath, key)
    }

    /**
     * Store the suggestions a Host response carried.
     * @param {unknown} payload - parsed response body.
     * @returns {number} how many suggestions were accepted.
     */
    function mergeSuggestions(payload) {
      const results = payload !== null && typeof payload === 'object' && Array.isArray(payload.results) ? payload.results : []
      const byPath = { ...autoStore.value.byPath }
      let accepted = 0
      for (const row of results) {
        if (row === null || typeof row !== 'object') continue
        const key = typeof row.key === 'string' && row.key !== '' ? row.key : row.path
        if (typeof key !== 'string' || key === '') continue
        const glyph = sanitizeGlyph(row.glyph)
        if (glyph === null) continue
        const why = normalizeWhy(row.why)
        byPath[key] = {
          entry: { kind: 'glyph', value: glyph },
          why,
          at: Date.now(),
          source: row.source === 'ai' ? 'ai' : 'rule',
        }
        accepted += 1
      }
      if (accepted === 0) return 0
      publishAuto({ ...autoStore.value, byPath: Object.freeze(byPath) })
      return accepted
    }

    /**
     * Ask the Host to analyse projects and store what comes back.
     * @param {readonly unknown[]} workspaces - projects to analyse.
     * @param {{force?: boolean}} [options] - `force` re-analyses even cached ones.
     * @returns {Promise<number>} how many suggestions were stored.
     */
    async function requestAutoSuggestions(workspaces, options = {}) {
      const list = Array.isArray(workspaces) ? workspaces.filter((item) => item !== null && typeof item === 'object') : []
      const force = options.force === true
      const targets = list.filter((workspace) => {
        const key = iconKey(workspace)
        if (key === '') return false
        if (force) {
          if (Object.hasOwn(iconStore.value, key)) return false
          return typeof workspace.path === 'string' && workspace.path.trim().startsWith('/')
        }
        return needsSuggestion(workspace)
      })
      if (targets.length === 0 || autoInflight) return 0
      if (typeof fetch !== 'function') return 0
      autoInflight = true
      publish(autoStore, { ...autoStore.value, running: true, error: '' })
      let accepted = 0
      try {
        const response = await fetch(SUGGEST_ROUTE, {
          method: 'POST',
          headers: { 'content-type': 'application/json' },
          body: JSON.stringify({
            language: currentLanguage(),
            projects: targets.map((workspace) => ({
              key: iconKey(workspace),
              path: typeof workspace.path === 'string' ? workspace.path : '',
              title: workspaceLabel(workspace, ''),
            })),
          }),
        })
        if (response === null || typeof response !== 'object' || response.ok !== true) {
          throw new Error(`suggest ${response === null ? 'no response' : response.status}`)
        }
        accepted = mergeSuggestions(await response.json())
        publish(autoStore, { ...autoStore.value, running: false, error: '' })
        return accepted
      } catch {
        autoFailedAt = Date.now()
        publish(autoStore, { ...autoStore.value, running: false, error: 'failed' })
        return accepted
      } finally {
        autoInflight = false
        if (autoStore.value.running === true) publish(autoStore, { ...autoStore.value, running: false })
      }
    }

    /**
     * Background entry point: analyse whatever is missing, at most every
     * {@link AUTO_RETRY_MS} per project, and stay silent unless it is enabled.
     * @param {readonly unknown[]} workspaces - live workspace list.
     */
    function maybeAutoSuggest(workspaces) {
      const state = autoStore.value
      if (state.enabled !== true || state.running || autoInflight) return
      if (Date.now() - autoFailedAt < AUTO_FAILURE_MS) return
      const now = Date.now()
      const targets = (Array.isArray(workspaces) ? workspaces : []).filter((workspace) => {
        if (!needsSuggestion(workspace)) return false
        const seen = autoSeenAt.get(iconKey(workspace)) ?? 0
        autoSeenAt.set(iconKey(workspace), now)
        return now - seen >= AUTO_RETRY_MS
      })
      if (targets.length === 0) return
      void requestAutoSuggestions(targets)
    }

    /**
     * Re-analyse one project on demand.
     * @param {unknown} workspace - target project.
     * @returns {Promise<number>} how many suggestions were stored.
     */
    function refreshAuto(workspace) {
      return requestAutoSuggestions([workspace], { force: true })
    }

    /**
     * Re-analyse every project on demand.
     * @param {readonly unknown[]} workspaces - live workspace list.
     * @returns {Promise<number>} how many suggestions were stored.
     */
    function refreshAllAuto(workspaces) {
      return requestAutoSuggestions(workspaces, { force: true })
    }

