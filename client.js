    /**
     * Modal picker opened by right-clicking a project row.
     * @param {object} props - `{ t, request, entry, onPick, onRemove, onClose }`.
     * @returns {import("react").ReactElement|null} the modal, or null when closed.
     */
    function ProjectIconPicker(props) {
      const request = props.request
      const t = props.t
      const suggestion = props.suggestion ?? null
      const panelRef = React.useRef(null)
      React.useEffect(() => {
        if (request === null) return undefined
        if (typeof document !== 'undefined' && typeof document.addEventListener === 'function') {
          const onKey = (event) => {
            if (event !== null && event.key === 'Escape') {
              if (typeof event.preventDefault === 'function') event.preventDefault()
              props.onClose()
            }
          }
          document.addEventListener('keydown', onKey, true)
          return () => document.removeEventListener('keydown', onKey, true)
        }
        return undefined
      }, [request === null])
      React.useEffect(() => {
        const node = panelRef.current
        if (node !== null && node !== undefined && typeof node.focus === 'function') node.focus()
      }, [request === null])
      // Remember what had focus when the picker opened and hand it back on close,
      // so a keyboard user is not dropped at the top of the document.
      const openerRef = React.useRef(null)
      React.useEffect(() => {
        if (request === null) return undefined
        const active = typeof document !== 'undefined' ? document.activeElement : null
        openerRef.current = active === null || active === undefined ? null : active
        return () => {
          const opener = openerRef.current
          openerRef.current = null
          if (opener === null || typeof opener.focus !== 'function' || opener.isConnected === false) return
          opener.focus()
        }
      }, [request === null])
      if (request === null) return null
      const workspace = request.workspace
      const label = workspaceLabel(workspace, '')
      return h(
        React.Fragment,
        null,
        h('div', { style: backdropStyle, onClick: props.onClose, 'aria-hidden': true }),
        h(
          'div',
          {
            ref: panelRef,
            role: 'dialog',
            'aria-modal': 'true',
            'aria-label': pick(t, 'settings.title'),
            tabIndex: -1,
            style: { ...panelStyle, outline: 'none' },
          },
          h(
            'div',
            { style: { display: 'flex', alignItems: 'center', gap: '8px' } },
            h(IconChip, { entry: props.entry, size: 22 }),
            h(
              'div',
              { style: { display: 'flex', flexDirection: 'column', minWidth: 0 } },
              h('div', { style: { fontSize: '13px', fontWeight: 600, ...ellipsisStyle } }, label),
              h(
                'div',
                { style: { fontSize: '10px', color: 'var(--dsw-alias-label-caption)', ...ellipsisStyle } },
                typeof workspace.path === 'string' ? workspace.path : '',
              ),
            ),
            h('div', { style: { flex: 1 } }),
            h('button', { type: 'button', onClick: props.onClose, style: ghostButtonStyle }, pick(t, 'picker.close')),
          ),
          h(
            'div',
            { style: { fontSize: '11px', color: 'var(--dsw-alias-label-tertiary)' } },
            pick(t, 'picker.hint'),
          ),
          suggestion === null
            ? null
            : h(SuggestionRow, {
                t,
                suggestion,
                onUse: () => props.onPick(suggestion.entry),
                onRefresh: props.onRefreshSuggestion,
                busy: props.suggestionBusy === true,
              }),
          h(IconEditor, { t, entry: props.entry, onPick: props.onPick, onRemove: props.onRemove }),
        ),
      )
    }

