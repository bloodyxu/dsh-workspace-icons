    /**
     * Nearest `data-row-key` on the event path.
     * @param {unknown} target - event target.
     * @returns {string|null} the row key, or null.
     */
    function rowKeyOf(target) {
      let node = target
      let guard = 0
      while (node !== null && node !== undefined && guard < 64) {
        guard += 1
        const key = typeof node.getAttribute === 'function' ? node.getAttribute('data-row-key') : null
        if (typeof key === 'string' && key !== '') return key
        node = node.parentElement ?? null
      }
      return null
    }

    /**
     * Resolve the workspace behind a right-clicked sidebar row. Only a project
     * header row counts: a session row (or anything else) owns the click.
     * @param {unknown} target - event target.
     * @returns {object|null} the live workspace, or null.
     */
    function workspaceFromEvent(target) {
      const key = rowKeyOf(target)
      if (typeof key !== 'string' || !key.startsWith(ROW_PREFIX)) return null
      const id = key.slice(ROW_PREFIX.length)
      if (id === '') return null
      const items = workspaceStore.value
      if (!Array.isArray(items)) return null
      return items.find((workspace) => workspace !== null && workspace.workspaceId === id) ?? null
    }

