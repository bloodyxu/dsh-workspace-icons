    // --- AI / rule suggestions --------------------------------------------

    /**
     * Clean a stored reason map.
     * @param {unknown} raw - persisted `why`.
     * @returns {{zh?: string, en?: string}|null} the cleaned map.
     */
    function normalizeWhy(raw) {
      if (raw === null || typeof raw !== 'object') return null
      const why = {}
      for (const lang of ['zh', 'en']) {
        const text = typeof raw[lang] === 'string' ? raw[lang].trim() : ''
        if (text !== '') why[lang] = text.slice(0, MAX_WHY)
      }
      return Object.keys(why).length === 0 ? null : why
    }

    /**
     * Normalize one stored suggestion.
     * @param {unknown} raw - persisted suggestion.
     * @returns {{entry: object, why: object|null, at: number, source: string}|null} the suggestion.
     */
    function normalizeSuggestion(raw) {
      if (raw === null || typeof raw !== 'object') return null
      const entry = normalizeEntry(raw.entry)
      if (entry === null) return null
      const at = typeof raw.at === 'number' && Number.isFinite(raw.at) ? raw.at : 0
      return { entry, why: normalizeWhy(raw.why), at, source: raw.source === 'ai' ? 'ai' : 'rule' }
    }

    /**
     * Read the persisted suggestion state.
     * @returns {{enabled: boolean, byPath: Readonly<Record<string, object>>}} state.
     */
    function readAutoState() {
      const empty = { enabled: true, byPath: EMPTY_ICONS }
      const area = storageArea()
      if (area === null) return empty
      let raw = null
      try {
        raw = area.getItem(AUTO_STORAGE_KEY)
      } catch {
        return empty
      }
      if (typeof raw !== 'string' || raw === '') return empty
      let parsed = null
      try {
        parsed = JSON.parse(raw)
      } catch {
        return empty
      }
      if (parsed === null || typeof parsed !== 'object') return empty
      const source = parsed.byPath
      if (source === null || typeof source !== 'object') return { ...empty, enabled: parsed.enabled !== false }
      const byPath = {}
      for (const [key, value] of Object.entries(source)) {
        if (typeof key !== 'string' || key === '') continue
        const suggestion = normalizeSuggestion(value)
        if (suggestion !== null) byPath[key] = suggestion
      }
      return {
        enabled: parsed.enabled !== false,
        byPath: Object.keys(byPath).length === 0 ? EMPTY_ICONS : Object.freeze(byPath),
      }
    }

    /**
     * Merge the manual icons with the suggestions; a manual icon always wins.
     * @param {Readonly<Record<string, object>>} manual - manual icon map.
     * @param {Readonly<Record<string, object>>} suggestions - suggestion map.
     * @returns {Readonly<Record<string, object>>} entry map for {@link buildCss}.
     */
    function mergeIcons(manual, suggestions) {
      const manualMap = manual !== null && typeof manual === 'object' ? manual : EMPTY_ICONS
      const suggestionMap = suggestions !== null && typeof suggestions === 'object' ? suggestions : EMPTY_ICONS
      let merged = null
      for (const [key, suggestion] of Object.entries(suggestionMap)) {
        if (Object.hasOwn(manualMap, key)) continue
        const entry = suggestion === null || typeof suggestion !== 'object' ? null : suggestion.entry
        if (entry === null || entry === undefined) continue
        merged = merged === null ? { ...manualMap } : merged
        merged[key] = entry
      }
      return merged === null ? manualMap : Object.freeze(merged)
    }

    /**
     * The suggestion stored for one workspace.
     * @param {string} key - icon key.
     * @returns {object|null} the suggestion, or null.
     */
    function suggestionFor(key) {
      if (typeof key !== 'string' || key === '') return null
      const byPath = autoStore.value.byPath
      return Object.hasOwn(byPath, key) ? byPath[key] : null
    }

    /**
     * The reason text in the reader's language.
     * @param {object|null} suggestion - stored suggestion.
     * @returns {string} the reason, or ''.
     */
    function whyText(suggestion) {
      if (suggestion === null || suggestion.why === null || typeof suggestion.why !== 'object') return ''
      const lang = currentLanguage()
      return suggestion.why[lang] ?? suggestion.why.zh ?? suggestion.why.en ?? ''
    }

    /**
     * The active harness language, as the two shipped dictionaries spell it.
     * @returns {'zh'|'en'} the language.
     */
    function currentLanguage() {
      const id =
        localeService !== undefined && localeService !== null && typeof localeService.getLocale === 'function'
          ? localeService.getLocale()
          : ''
      if (typeof id === 'string' && id.toLowerCase().startsWith('en')) return 'en'
      if (typeof navigator !== 'undefined' && typeof navigator?.language === 'string') {
        if (navigator.language.toLowerCase().startsWith('en')) return 'en'
      }
      return 'zh'
    }

    /**
     * Publish suggestion state and persist the durable part of it.
     * @param {object} next - next auto store value.
     */
    function publishAuto(next) {
      publish(autoStore, next)
      const area = storageArea()
      if (area !== null) {
        try {
          area.setItem(
            AUTO_STORAGE_KEY,
            JSON.stringify({ v: SCHEMA_VERSION, enabled: next.enabled, byPath: capEntries(next.byPath) }),
          )
        } catch {
          /* storage full or blocked — the in-memory state still works */
        }
      }
      syncStyle()
    }

